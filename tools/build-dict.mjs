#!/usr/bin/env node
// Merge dict/zh-CN/*.json into runtime/dict.js (the file the browser loads).
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const dir = path.join(root, "dict/zh-CN");
const merged = {};
let dupes = 0;
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort()) {
  const data = JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"));
  for (const [en, zh] of Object.entries(data)) {
    if (typeof zh !== "string" || !zh.trim()) continue;
    if (en in merged && merged[en] !== zh) {
      dupes++;
      console.warn(`conflict in ${f}: ${JSON.stringify(en)}: ${JSON.stringify(merged[en])} vs ${JSON.stringify(zh)}`);
    }
    merged[en] = zh;
  }
}
const pkg = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
merged.__version__ = `${pkg.version ?? "0"}+${Object.keys(merged).length}`;
fs.writeFileSync(
  path.join(root, "runtime/dict.js"),
  `// Generated by tools/build-dict.mjs from dict/zh-CN/*.json. Do not edit.\nwindow.__T3ZH_DICT__ = ${JSON.stringify(merged)};\n`,
);
console.log(`runtime/dict.js: ${Object.keys(merged).length - 1} entries${dupes ? `, ${dupes} conflicts` : ""}`);
